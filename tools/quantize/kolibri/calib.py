"""Stage `calib` of tools/quantize_kolibri1.sh: the calibration set and the held-out evaluation sets
exactly per spec 20 §3.1.

    calib.py --model <snapshot> --out <dir> [--nsamples 1024] [--seqlen 2048] [--backend auto|vllm|hf]

Rows are SEQLEN tokens, every one starting at a conversation boundary (common.pack), all
chat-formatted through the model's own template (reasoning on: the template's default, effort
"high"). Base mix by rows (common.CAT_FRACTIONS): German 50 % (chat 20 %, tool calls 10 %, long
documents 20 %), English chat 30 %, code 20 %. The assistant turns are self-generated by the bf16
model with its published sampling (T 1.0, top-p 0.97, top-k 128): German / English / code prompts
from prompts/*.jsonl (their `calib` split); tool scenarios run two turns (the model's <tool_call>,
the scenario's canned <tool_response>, the model's answer); document rows put a German Wikipedia
article (pinned revision, shard 00000) under one of prompts/de_doc_tasks.jsonl's instructions.

Held-out sets for `eval` (never calibrated on): de_wiki - raw article text from shard 00019; de_chat,
en_chat, code - the prompts' `eval` split, answered the same way. Writes calib.safetensors,
eval_<set>.safetensors and calib_manifest.json under --out.
"""
