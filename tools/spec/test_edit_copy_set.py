"""Tests for edit_copy_set.py (spec 19f).

    python3 tools/spec/test_edit_copy_set.py   (or python3 -m pytest tools/spec)

A stub tokenizer (prefix-stable, 4 characters an id) builds the set at small depths: sizes, source spans, distances,
determinism, the refusal of a near source. The committed set (tests/golden/edit-copy) is checked without a tokenizer.
"""
import json
import os
import sys
import tempfile
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import edit_copy_set as ec  # noqa: E402

SET_DIR = os.path.join(ec.ROOT, "tests", "golden", "edit-copy")
SMALL = {"8k": 6000, "32k": 9000, "64k": 12000, "99k": 15000}


class StubTok:
    """Renders each message on its own (so the render is prefix-stable, as Qwen3.8's template is over these turns),
    4 characters an id."""

    def apply_chat_template(self, msgs, tools=None, add_generation_prompt=True, enable_thinking=False, tokenize=True):
        parts = [f"<{m['role']}>{m.get('content', '')}{json.dumps(m.get('tool_calls', ''))}</>" for m in msgs]
        if add_generation_prompt:
            parts.append("<assistant>")
        return [zlib.crc32(p[i:i + 4].encode()) & 0xFFFF for p in parts for i in range(0, len(p), 4)]


def build_small(out, **kw):
    return ec.build_set(StubTok(), out, tools=[], depths=SMALL, min_distance=500, **kw)


def test_small_set_sizes_spans_distances():
    with tempfile.TemporaryDirectory() as d:
        manifest = build_small(d)
        assert len(manifest) == 12
        assert sorted({e["kind"] for e in manifest}) == ["quote", "reemit", "rename"]
        for e in manifest:
            t = SMALL[e["depth"]]
            assert t * (1 - ec.DEPTH_TOL) <= e["ids"] <= t
            s0, s1 = e["source_span"]
            assert 0 < s0 < s1 < e["ids"]
            assert e["distance"] == e["ids"] - s1 > 500
            with open(os.path.join(d, e["name"] + ".json")) as f:
                rec = json.load(f)
            msgs = rec["messages"]
            assert msgs[0]["role"] == "system" and msgs[-1]["role"] == "user"
            assert msgs[3]["role"] == "tool"   # the source: the first tool result
            # the source's text is what the last turn asks for: its span renders the source message
            src_ids = StubTok().apply_chat_template(msgs[:4], add_generation_prompt=False)
            assert len(src_ids) == s1
        _, problems = ec.check_set(d, depths=SMALL, min_distance=500)
        assert problems == []


def test_deterministic():
    with tempfile.TemporaryDirectory() as a, tempfile.TemporaryDirectory() as b:
        assert build_small(a) == build_small(b)


def test_near_source_refused():
    # with the window as large as the depth, no source can lie beyond it
    with tempfile.TemporaryDirectory() as d:
        try:
            ec.build_set(StubTok(), d, tools=[], depths={"8k": 6000}, min_distance=6000)
        except SystemExit as e:
            assert "not beyond the drafter's window" in str(e)
        else:
            raise AssertionError("a near source was accepted")


def test_check_catches_a_tampered_file():
    with tempfile.TemporaryDirectory() as d:
        build_small(d)
        p = os.path.join(d, "quote-8k.ids")
        with open(p) as f:
            ids = f.read().split()
        with open(p, "w") as f:
            f.write(" ".join(ids[:-1]) + "\n")
        _, problems = ec.check_set(d, depths=SMALL, min_distance=500)
        assert any("quote-8k" in p for p in problems)


def test_committed_set():
    if not os.path.exists(os.path.join(SET_DIR, "manifest.json")):
        return   # generated by edit_copy_set.py with the checkpoint's tokenizer (plan 19f Task 4)
    manifest, problems = ec.check_set(SET_DIR)
    assert problems == []
    assert len(manifest) == 12
    assert {e["depth"] for e in manifest} == set(ec.DEPTHS)


