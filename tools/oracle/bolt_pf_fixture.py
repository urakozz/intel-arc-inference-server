"""The Nemotron 3.5 Bolt PREFILL fixture (spec 25d Task 1): 25a's training-kernel functions over a chunk
(tools/oracle/bolt_mamba_ops.py conv_seq and ssm_chunk - the SSD form the reference runs) on deterministic inputs at the
real widths, written as a C++ header that tests/kernels/bolt_pf_ref_test.cc holds tests/kernels/bolt_pf_ref.h's chunk twin
to.

    tools/oracle/bolt_pf_fixture.py > tests/kernels/bolt_pf_fixture.h

Run in the oracle container with 25a's 5.19.0 site first on PYTHONPATH (seconds, < 4 GB, no checkpoint; on the Mac under
the CPU lock /tmp/b70-cpu-model.lock):

    docker run --rm --memory 16g --cpus 4 -v "$PWD:/ws" -w /ws -v <main checkout>/oracle-out-q4exp/site:/site:ro \\
      -e PYTHONPATH=/site --entrypoint python3 agnes-ref-img:latest tools/oracle/bolt_pf_fixture.py > tests/kernels/bolt_pf_fixture.h

The inputs come from bolt_fixture.py's hash (boltref::fixture_val / fixture_f32 in C++); A = -exp(A_log) is the ENGINE's
(bolt_mamba_ops A_EXP "engine": the twin takes A from the engine's arithmetic - plan 25c's dependency). The cases:

  (a) conv over a chunk   181 positions of raw xBC fine (t 60, seed 11, amp 2, index p x 10240 + c), w fine (t 21, seed
                          11, amp 0.5, index c x 4 + j - tap 0 the OLDEST), bias fine (t 22, seed 11, amp 0.5): conv_seq over
                          the whole 181 from a zero history, asserted equal (torch) to conv_seq over [0, 117) then [117, 181)
                          with the last three raw columns carried - xc at the rows kConvRows on the channels c % 5 == 0
  (b) the SSD scan        181 rows (sub-chunks 64 + 64 + 53 from position 0): xc fine (t 61, seed 12, index t x 10240 + c),
                          dt_raw fine (t 62, amp 2, index t x 128 + h), dt_bias fine (t 63, amp 4) with heads 0 / 1 / 6 =
                          -10.5 / 8.5 / -11.6875, A_log fine (t 64, amp 4) with heads 2..5 = bf16(-4.66 / 4.41 / 8.81 /
                          -6.81), D fine (t 65, amp 2), the initial state f32 (t 66, index (h x 64 + p) x 128 + n): ssm_chunk
                          at chunk 64 (the engine's sub-chunk) and at 128 (the config's training chunk) - y at kSsdRows x
                          kSsdHeads [.][64] and the final state at kSsdHeads x p {0, 17, 63} [.][128]
"""
import importlib.util
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:] = [p for p in sys.path if os.path.abspath(p or os.getcwd()) != _HERE]

import torch  # noqa: E402


def _load(name):
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, os.path.join(_HERE, f"{name}.py"))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


fx = _load("bolt_fixture")
ops = fx.ops
BF, F32 = torch.bfloat16, torch.float32
HEADS, P, N, G, CONV, XBC, INNER = fx.HEADS, fx.P, fx.N, fx.G, fx.CONV, fx.XBC, fx.INNER
T = 181
CONV_SPLIT = 117
CONV_STRIDE = 5
CONV_ROWS = [0, 1, 2, 3, 63, 64, 116, 117, 118, 119, 180]
SSD_HEADS = [0, 1, 2, 3, 4, 5, 6, 77, 127]
SSD_ROWS = [0, 1, 2, 62, 63, 64, 65, 127, 128, 129, 180]
SSD_P = [0, 17, 63]


def main() -> None:
    torch.set_num_threads(max(1, min(4, torch.get_num_threads())))
    out = [
        "#pragma once",
        f"// GENERATED by tools/oracle/bolt_pf_fixture.py in agnes-ref-img:latest (torch {torch.__version__}, CPU capability "
        f"{torch.backends.cpu.get_cpu_capability()}, transformers {fx.ref_version()}) - do not edit.",
        "// Command: docker run --rm --memory 16g --cpus 4 -v \"$PWD:/ws\" -w /ws -v <25a's 5.19.0 site>:/site:ro -e "
        "PYTHONPATH=/site --entrypoint python3 agnes-ref-img:latest tools/oracle/bolt_pf_fixture.py > tests/kernels/bolt_pf_fixture.h",
        "// tools/oracle/bolt_mamba_ops.py's conv_seq / ssm_chunk (A by the engine's exp) on boltref::fixture_val's inputs;",
        "// 4 hex digits per bf16 value, 8 per fp32. The script's docstring has the cases.",
        "namespace bolt_pf_fixture {",
        f"inline constexpr unsigned kT = {T}, kConvSplit = {CONV_SPLIT}, kConvStride = {CONV_STRIDE};",
    ]

    # (a) the conv over a chunk, the state carried ----------------------------------------------------------------
    X = fx.bf(fx.vals(False, 60, T * XBC, 11, amp=2.0).reshape(T, XBC))
    cw = fx.bf(fx.vals(False, 21, XBC * CONV, 11, amp=0.5).reshape(XBC, CONV))
    cb = fx.bf(fx.vals(False, 22, XBC, 11, amp=0.5))
    xt = X.t()[None].contiguous()                                                   # [1][C][T]
    whole = ops.conv_seq(xt, cw, cb, None)[0].t()                                   # [T][C] bf16
    first = ops.conv_seq(xt[..., :CONV_SPLIT].contiguous(), cw, cb, None)[0].t()
    state = xt[..., CONV_SPLIT - (CONV - 1):CONV_SPLIT].contiguous()                # the last three RAW columns
    second = ops.conv_seq(xt[..., CONV_SPLIT:].contiguous(), cw, cb, state)[0].t()
    assert torch.equal(torch.cat([first, second]), whole), "conv_seq: a chunk with the state carried != the whole"
    sub = torch.arange(0, XBC, CONV_STRIDE)
    out.append("// (a) conv over a chunk: xc [rows kConvRows][10240 / 5] (channels c % 5 == 0), the whole 181 = [0, 117) +")
    out.append("//     [117, 181) with the last three raw columns carried (asserted in torch)")
    out.append("inline constexpr unsigned kConvRows[] = {" + ", ".join(map(str, CONV_ROWS)) + "};")
    out.append(fx.hexs("kConvXc", fx.bits16(whole[CONV_ROWS][:, sub]), 4))

    # (b) the SSD scan ------------------------------------------------------------------------------------------------
    xc = fx.bf(fx.vals(False, 61, T * XBC, 12).reshape(T, XBC))
    dt_raw = fx.bf(fx.vals(False, 62, T * HEADS, 12, amp=2.0).reshape(T, HEADS))
    dt_bias = fx.vals(False, 63, HEADS, 12, amp=4.0)
    dt_bias[0], dt_bias[1], dt_bias[6] = -10.5, 8.5, -11.6875
    A_log = fx.vals(False, 64, HEADS, 12, amp=4.0)
    for hh, v in ((2, -4.66), (3, 4.41), (4, 8.81), (5, -6.81)):
        A_log[hh] = float(torch.tensor(v).to(BF))
    D = fx.vals(False, 65, HEADS, 12, amp=2.0)
    S0 = fx.f32vals(66, HEADS * P * N, 12).reshape(HEADS, P, N)
    A = ops.A_from_log(A_log.to(BF), "engine")
    x = xc[:, :INNER].reshape(T, HEADS, P)
    Bm = xc[:, INNER:INNER + G * N].reshape(T, G, N)
    Cm = xc[:, INNER + G * N:].reshape(T, G, N)
    out.append("// (b) SSD: y [kSsdRows][kSsdHeads][64] and the final state [kSsdHeads][p 0 / 17 / 63][128], ssm_chunk at")
    out.append("//     sub-chunks of 64 (the engine's, from position 0) and of 128 (the config's training chunk); A [128]")
    out.append("inline constexpr unsigned kSsdHeads[] = {" + ", ".join(map(str, SSD_HEADS)) + "};")
    out.append("inline constexpr unsigned kSsdRows[] = {" + ", ".join(map(str, SSD_ROWS)) + "};")
    out.append("inline constexpr unsigned kSsdP[] = {" + ", ".join(map(str, SSD_P)) + "};")
    out.append(fx.hexs("kSsdA", fx.bits32(A), 8))
    for chunk in (64, 128):
        y, S = ops.ssm_chunk(x, dt_raw, A, Bm, Cm, D, dt_bias, S0, chunk=chunk)
        ysel = y[SSD_ROWS][:, SSD_HEADS]                                             # [rows][heads][64]
        Ssel = S[SSD_HEADS][:, SSD_P]                                                # [heads][3][128]
        out.append(fx.hexs(f"kSsdY{chunk}", fx.bits16(ysel), 4))
        out.append(fx.hexs(f"kSsdState{chunk}", fx.bits32(Ssel), 8))
    out.append("}  // namespace bolt_pf_fixture")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
