"""The LFM2.5-24B-A2B RoPE fixture (spec 24b Task 3): transformers 5.19.0's own
`Lfm2MoeRotaryEmbedding` (theta 1e7, head_dim 64, rope_type "default") at positions 0, 1, 2, 4095,
131071 and 1000 random ones in [0, 131072), written as a C++ header `loader::lfm_rope_table` is held
to bitwise (tests/loader/lfm2moe_rope_test.cc).

    tools/oracle/lfm2moe_rope_fixture.py > tests/loader/lfm2moe_rope_fixture.h

Run with transformers 5.19.0 on PYTHONPATH (tools/oracle/qwen4exp_env.sh's site), e.g. inside
agnes-ref-img:

    PYTHONPATH=/ws/oracle-out-q4exp/site python3 tools/oracle/lfm2moe_rope_fixture.py > \\
      tests/loader/lfm2moe_rope_fixture.h
"""
import importlib.util
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:] = [p for p in sys.path if os.path.abspath(p or os.getcwd()) != _HERE]

import torch  # noqa: E402

_spec = importlib.util.spec_from_file_location("lfm2moe_ref", os.path.join(_HERE, "lfm2moe_ref.py"))
ref = importlib.util.module_from_spec(_spec)
sys.modules["lfm2moe_ref"] = ref
_spec.loader.exec_module(ref)

FIXED = [0, 1, 2, 4095, 131071]
N_RANDOM = 1000
SEED = 24


def bits16(x: torch.Tensor) -> list:
    return (x.contiguous().to(torch.bfloat16).view(torch.int16).flatten().int() & 0xFFFF).tolist()


def hexs(name: str, xs: list) -> str:
    h = "".join(f"{v:04x}" for v in xs)
    lines = [f'    "{h[i:i + 128]}"' for i in range(0, len(h), 128)]
    return f"inline constexpr char {name}[] =\n" + "\n".join(lines) + ";\n"


def main() -> None:
    m = ref.mm()
    cfg = ref.config(None, raw={
        "model_type": "lfm2_moe", "hidden_size": 2048, "num_attention_heads": 32, "num_key_value_heads": 8,
        "max_position_embeddings": 131072, "rope_parameters": {"rope_type": "default", "rope_theta": 1e7},
        "num_hidden_layers": 1, "layer_types": ["full_attention"], "num_dense_layers": 1, "intermediate_size": 64,
        "moe_intermediate_size": 64, "num_experts": 1, "num_experts_per_tok": 1, "vocab_size": 8, "conv_L_cache": 3,
        "conv_bias": False, "norm_eps": 1e-5, "use_expert_bias": True, "norm_topk_prob": True,
        "routed_scaling_factor": 1.0, "tie_word_embeddings": True, "bos_token_id": 0, "eos_token_id": 1,
        "pad_token_id": 2,
    })
    rope = m.Lfm2MoeRotaryEmbedding(cfg)
    g = torch.Generator().manual_seed(SEED)
    rand_pos = torch.randint(0, 131072, (N_RANDOM,), generator=g).tolist()
    positions = FIXED + rand_pos
    pos = torch.tensor(positions, dtype=torch.long)[None]            # [1, P]
    x = torch.zeros(1, 1, dtype=torch.bfloat16)
    cos, sin = rope(x, pos)                                          # [1, P, 64] bf16
    half = cos.shape[-1] // 2
    out = [
        "#pragma once",
        "// GENERATED by tools/oracle/lfm2moe_rope_fixture.py against transformers "
        "5.19.0's Lfm2MoeRotaryEmbedding - do not edit.",
        "// theta 1e7, head_dim 64 (rope_type default): 5 fixed positions then 1000 random ones, seed 24.",
        "namespace lfm2moe_rope_fixture {",
        f"inline constexpr unsigned kN = {len(positions)}, kHalf = {half};",
        "inline constexpr unsigned kPos[] = {" + ", ".join(map(str, positions)) + "};",
        hexs("kCos", bits16(cos[0, :, :half])),
        hexs("kSin", bits16(sin[0, :, :half])),
        "}  // namespace lfm2moe_rope_fixture",
    ]
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
