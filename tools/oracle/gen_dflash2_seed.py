"""Write the DFlash 2 drafter's calibration seed table into the engine (CPU only).

    gen_dflash2_seed.py [accept.json] [--out header]

Reads the CPU job's per-anchor records (default
$B70_DATA/oracle-out/inkling/df2-stop/accept.int8h.json, variant int8h-c64) and writes
src/server/dflash2_calib_seed.h (default): the measured conditional acceptance rate per (draft
position 0..6, probability bin 0..8, server::DraftCalib's bins) over the tested drafts - a draft at
position i counts as tested only when every draft before it was accepted; censored anchors are
skipped - with how many samples each cell holds.

The seed split, named here and in price_stop.py: the seed comes from the a4 tool-call sets plus
code and chat only; the agentic, code-kv8 and prose sets are held out for the check, never the seed.
Re-run on the box: the committed header is byte for byte what this writes.
"""
import os
import sys

# this directory holds tokenize.py, which would shadow the stdlib's when run as a script
_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:] = [p for p in sys.path if os.path.abspath(p or os.getcwd()) != _HERE]

import argparse  # noqa: E402
import importlib.util  # noqa: E402


def _load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(_HERE, name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


ps = _load("price_stop")

HEADER = """#pragma once
// Generated by tools/oracle/gen_dflash2_seed.py - do not edit. Re-run it on the box (it reads
// $B70_DATA/oracle-out/inkling/df2-stop/accept.int8h.json, variant int8h-c64) to reproduce this
// table byte for byte. The seed split, named in the generator: the a4 tool-call sets plus code and
// chat seed the table; the agentic, code-kv8 and prose sets are held out for the check only.
// server::DraftCalib takes this table as the DFlash 2 drafter's prior: a cell with at least
// kSeedMinN samples holds the measured rate over its n tested drafts (a draft at position i counts
// as tested only when every draft before it was accepted; censored anchors skipped).
#include <array>

#include "server/step_k.h"

namespace server {

inline constexpr DraftCalib::SeedTable kDflash2CalibSeed{{
{rows}
}};

}  // namespace server
"""

def render(seed):
    rows = []
    for i, row in enumerate(seed):
        cells = ", ".join("{{{:.6f}f, {}u}}".format(c[0], c[1]) for c in row)
        rows.append(f"    // position {i}\n    {cells},")
    return HEADER.replace("{rows}", "\n".join(rows))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("json", nargs="?",
                    default=os.path.join(os.environ.get("B70_DATA", "/nonexistent"),
                                         "oracle-out/inkling/df2-stop/accept.int8h.json"))
    ap.add_argument("--variant", default="int8h-c64")
    ap.add_argument("--out", default=os.path.normpath(os.path.join(
        _HERE, os.pardir, os.pardir, "src", "server", "dflash2_calib_seed.h")))
    args = ap.parse_args()
    out = os.path.normpath(args.out)
    text = render(ps.seed_table(ps.load_anchors(args.json, args.variant)))
    with open(out, "w") as f:
        f.write(text)
    print(f"wrote {out}")


if __name__ == "__main__":
    sys.exit(main())
