#!/usr/bin/env python3
"""tools/probe/mk_offload_kernel.py - spec 22a (P0.3): the expert kernels read through a pointer table.

Writes tools/probe/probe_offload_moe.cl from src/kernels/qwen4exp/q4_moe.cl with EXACTLY the two expert-address
lines replaced - spec 22's indirection table in the form plan 22b's engine will bind:

    #define Q4_EXPERT_GU(base, id) ((base) + (size_t)(id) * UP_BLK_U32)
    #define Q4_EXPERT_DN(base, id) ((base) + (size_t)(id) * DN_BLK_U32)
  ->
    #define Q4_EXPERT_GU(base, id) ((__global const uint*)(intptr_t)((__global const ulong*)(base))[(id)])
    #define Q4_EXPERT_DN(base, id) ((__global const uint*)(intptr_t)((__global const ulong*)(base))[(id)])

`base` is then the layer's u64 table: gate||up pointers [0, 512), down pointers [512, 1024) - the gate_up launch is
bound at the table, the down launch at table + 512 entries. A pointer is a VRAM slot or a host-USM address; every
other token of q4_moe.cl (the route, the work-group geometry, the arithmetic) is unchanged, so the probe's zero-copy
arm reads host USM exactly as the engine would.

    mk_offload_kernel.py           write the generated file
    mk_offload_kernel.py --check   compare instead (the drift test: probe_offload_kernel_drift_test)

Exits non-zero when either line is missing or appears more than once (the generator refuses anything else), or,
with --check, when the committed file differs from what it would write.
"""
import argparse
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = "src/kernels/qwen4exp/q4_moe.cl"
OUT = "tools/probe/probe_offload_moe.cl"

LINES = {
    "#define Q4_EXPERT_GU(base, id) ((base) + (size_t)(id) * UP_BLK_U32)":
        "#define Q4_EXPERT_GU(base, id) ((__global const uint*)(intptr_t)((__global const ulong*)(base))[(id)])",
    "#define Q4_EXPERT_DN(base, id) ((base) + (size_t)(id) * DN_BLK_U32)":
        "#define Q4_EXPERT_DN(base, id) ((__global const uint*)(intptr_t)((__global const ulong*)(base))[(id)])",
}


def generate(src_text: str) -> str:
    lines = src_text.split("\n")
    for old in LINES:
        n = sum(1 for ln in lines if ln == old)
        if n != 1:
            raise SystemExit(f"mk_offload_kernel: {SRC} holds the line\n  {old}\n{n} times (expected exactly once) - "
                             "the expert address moved; update this generator and plan 22a's Review Focus 1")
    # Any other line defining either macro is a second address path the table would not cover.
    for ln in lines:
        s = ln.lstrip()
        if (s.startswith("#define Q4_EXPERT_GU") or s.startswith("#define Q4_EXPERT_DN")) and ln not in LINES:
            raise SystemExit(f"mk_offload_kernel: {SRC} defines an expert address outside the two lines:\n  {ln}")
    out = [LINES.get(ln, ln) for ln in lines]
    sha = hashlib.sha256(src_text.encode("utf-8")).hexdigest()
    head = [
        "// GENERATED by tools/probe/mk_offload_kernel.py - do not edit; rerun it (probe_offload_kernel_drift_test",
        "// checks the committed copy). Spec 22a (P0.3): " + SRC + " with exactly its two expert-address lines",
        "// (Q4_EXPERT_GU / Q4_EXPERT_DN) replaced by a u64 pointer-table read - `w` is the layer's table: gate||up",
        "// pointers [0, 512), down pointers [512, 1024); the down launch is bound at table + 512 entries.",
        "// source sha256 " + sha,
    ]
    return "\n".join(head) + "\n" + "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="compare with the committed file instead of writing it")
    a = ap.parse_args()
    with open(os.path.join(ROOT, SRC), encoding="utf-8") as f:
        text = generate(f.read())
    path = os.path.join(ROOT, OUT)
    if a.check:
        try:
            with open(path, encoding="utf-8") as f:
                have = f.read()
        except FileNotFoundError:
            print(f"mk_offload_kernel --check: FAIL - {OUT} is missing (run tools/probe/mk_offload_kernel.py)")
            return 1
        if have != text:
            hl, tl = have.split("\n"), text.split("\n")
            first = next((i for i in range(min(len(hl), len(tl))) if hl[i] != tl[i]), min(len(hl), len(tl)))
            print(f"mk_offload_kernel --check: FAIL - {OUT} differs from the generator's output at line {first + 1} "
                  f"(rerun tools/probe/mk_offload_kernel.py and commit it)")
            return 1
        print(f"mk_offload_kernel --check: OK - {OUT} is {SRC} with its two expert-address lines as the table form")
        return 0
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"mk_offload_kernel: wrote {OUT} ({len(text)} B)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
