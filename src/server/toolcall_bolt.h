#pragma once

// Spec 25e (spec 25 §7): Nemotron 3.5 Bolt's reasoning and Qwen3-Coder XML tool calls in the generated text.
//
// The reasoning is the `ultra_v3` reasoning parser's (ultra_v3_reasoning_parser.py, sha256 14e03de5..., which both Bolt repos
// ship: vLLM's DeepSeek-R1 parser plus three rules; ideas only - no code is copied). It follows the PROMPT's end, per request:
//   - the prompt ends "<think>\n" (thinking on, the default): the output OPENS INSIDE reasoning, up to the first "</think>"
//     (a second one is content). The reasoning is VERBATIM - no whitespace is stripped from either side, no leading newline
//     dropped - because the template re-renders a turn as "<think>\n" + reasoning_content + "</think>" + content: a stripped
//     reasoning would drift every later prompt from the generated bytes and miss the prefix cache (spec 25 §7). (ultra_v3's
//     third rule - one leading newline dropped when the output carries a <think> of its own - is for offline re-parsing of
//     a full assistant span; live output never carries the start token, so it is not applied and text before / including a
//     stray <think> stays reasoning.)
//   - the prompt ends "<think></think>" (enable_thinking false): there is no reasoning channel; EVERYTHING is content, a stray
//     "</think>" the model echoes included (ultra_v3's first rule);
//   - force_nonempty_content (the request's chat_template_kwargs, `true` exactly): reasoning that ends with no content - no
//     "</think>", or nothing after it - becomes content (ultra_v3's second rule; DeepSeek-R1's `content or None` makes a
//     bare "</think>" at the end count as no content, and any byte after it - whitespace included - as content). The moved
//     text is plain content: a tool call written in unfinished reasoning is never executed (vLLM would run its tool parser
//     over it). So that the rule can be decided at the end of the text, a stream with the flag set HOLDS the reasoning until
//     the first byte after "</think>" (or the end of generation) arrives: it streams no reasoning before then. Any split of
//     the output still yields the same deltas in concatenation.
// After "</think>" (or from the first byte when thinking is off) the text is the Qwen XML parser's (server/toolcall.h's
// OutputStream, unchanged but for one option): content, and <tool_call>\n<function=NAME>\n<parameter=KEY>\nVALUE\n
// </parameter>...</function>\n</tool_call> calls typed by the request's schema first. A <tool_call> inside reasoning is
// reasoning. A call cut by the end of generation (max_tokens, EOS) - one whose </function> never closed - is neither a call
// nor content (spec 23 decision 16's rule: an agent must never execute a truncated edit); a stop string never reaches
// finish(), so a call cut by one is dropped the same way. Pure host code: no engine, no tokenizer.

#include <string>
#include <vector>

#include <nlohmann/json.hpp>

#include "server/toolcall.h"

namespace server {

class BoltOutputStream : public OutputParser {
 public:
  // thinking: the prompt ended in "<think>\n". force_nonempty_content: the request's kwarg (true exactly).
  BoltOutputStream(bool thinking, bool force_nonempty_content, nlohmann::json tools);
  std::vector<Delta> push(const std::string& piece) override;
  std::vector<Delta> finish() override;

 private:
  enum class Phase { Reasoning, Body };
  void run(std::vector<Delta>& out, bool final);
  static void reasoning(std::vector<Delta>& out, const std::string& text);
  static void content(std::vector<Delta>& out, const std::string& text);

  Phase phase_;
  bool force_;
  std::string buf_;        // Reasoning: the text not yet decided; held in full while force_ is set
  bool closed_ = false;    // Reasoning with force_: "</think>" has been seen (buf_ holds the reasoning up to it)
  size_t scanned_ = 0;     // force_, not closed: buf_[0, scanned_) holds no "</think>" start (M3: no rescan from 0)
  size_t reasoning_len_ = 0;  // closed_: the reasoning's length in buf_; what follows it is content
  OutputStream body_;
};

// The whole-text parse (BoltOutputStream over one piece).
ParsedOutput parse_bolt_output(const std::string& text, bool thinking, bool force_nonempty_content,
                               const nlohmann::json& tools);

}  // namespace server
