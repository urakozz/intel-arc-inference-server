#pragma once

// LFM2.5-24B-A2B's reasoning and pythonic tool calls in the generated text (spec 24e, spec 24 section 4.6).
//
// The chat template (chat_template.jinja) ends the generation prompt in "<|im_start|>assistant\n<think>", so the
// output OPENS INSIDE REASONING and runs to "</think>"; what follows is content, verbatim, and tool calls:
//   <|tool_call_start|>[name(key=value, ...), name2(...)]<|tool_call_end|>
// (both tags are added tokens that are not special, so they are in the text as the server detokenises). The
// template's format_arg_value writes a top-level string argument single-quoted with \\ \' \n \r escaped, and a list
// or dict argument through tojson; int, float, True / False / None as Python writes them. This file reads that back
// with a hand-written literal parser (never eval, no regex): a value is a string, a number, True / False / None (JSON's
// true / false / null too), a list, a tuple or a dict, nested at most 64 deep.
//
// Reading, whole text and streamed alike (the concatenation of the deltas of any split of a text equals the parse of the
// whole, call ids aside - spec 7a's rule):
//   - reasoning: verbatim up to the first "</think>", no byte stripped from either side (the template writes
//     "<think>" + reasoning + "</think>" back, so a client that returns the parsed turn re-renders the generated bytes).
//     A "<|tool_call_start|>" inside reasoning is reasoning text. Generation that ends inside reasoning is reasoning;
//   - content: everything outside reasoning and tool-call blocks, verbatim (whitespace included);
//   - a block "<|tool_call_start|> ... <|tool_call_end|>": each call is emitted once, as soon as its ')' has arrived and
//     the text after it has settled how its last string ended (at the latest when the block ends; the rest of the block's
//     text is held back); a block without a single valid call is CONTENT, verbatim with its tags; after a valid call the
//     first thing that is not a call ends the block, and that tail is dropped (never content);
//   - a block cut by the end of generation (max_tokens, EOS) emits the calls whose ')' closed; the unfinished tail is
//     dropped, and a cut block with no closed call produces nothing at all (its text is not content);
//   - a "<|tool_call_end|>" with no open block is dropped.
// Lenient reading beyond what the template writes (spec 24 section 4.6, decision 7); each rule is counted in
// PythonicRules, per request, for --log-requests:
//   - a quote inside a string that is not followed (after whitespace) by what the grammar allows after the string is
//     part of the string ('it's a test'); quote_recovered counts those quotes;
//   - quoted function and argument names are stripped ('read_file'(...), "path"="x"); quoted_name;
//   - a call without the list brackets; bare_call;
//   - JSON's true / false / null as a keyword argument's value; json_literal;
//   - a lone positional dict as the arguments object; positional_dict;
//   - a tail dropped after a valid call, or a cut block; dropped_unfinished;
//   - a stray "<|tool_call_end|>"; stray_end.
// Not lenient (the call is invalid): a positional argument that is not a lone dict, a name without '=' or '=' without a
// value, inf / nan / a bare name, an unterminated string or container, a missing comma between arguments or calls.
// A block is read up to its first 1 MiB only: the calls that closed there are kept and the rest is a dropped tail; with
// none, a complete block is content (spec 24 section 4.6: "a block > 1 MiB is content"), a cut one nothing.
// Pure host code: no engine, no tokenizer.

#include <cstdint>
#include <memory>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

#include <nlohmann/json.hpp>

#include "server/toolcall.h"

namespace server {

struct PythonicRules {
  uint32_t quote_recovered = 0, quoted_name = 0, bare_call = 0, json_literal = 0, positional_dict = 0,
           dropped_unfinished = 0, stray_end = 0;
  PythonicRules& operator+=(const PythonicRules& o);
};

// One block's text between <|tool_call_start|> and <|tool_call_end|> (exclusive). `complete`: the end tag was seen
// (false: generation ended inside the block). Returns the calls (ids from `seed`), or nullopt when `complete` and the
// block holds no valid call (the caller keeps the block as content). A cut block with no closed call returns an empty
// vector. The rules that fired are added to `rules`.
std::optional<std::vector<ToolCall>> parse_pythonic_calls(std::string_view block, bool complete, uint64_t& seed,
                                                          PythonicRules& rules);

// `reasoning_first`: the prompt ended in "<think>" (ChatFormat::Lfm2's template always does), so the output opens inside
// reasoning. `tools` are accepted for the OutputParser factory's signature and do not type the arguments: the literals do.
class Lfm2OutputStream : public OutputParser {
 public:
  explicit Lfm2OutputStream(nlohmann::json tools, bool reasoning_first = true);
  ~Lfm2OutputStream() override;
  std::vector<Delta> push(const std::string& piece) override;
  std::vector<Delta> finish() override;
  const PythonicRules& rules() const { return rules_; }
  nlohmann::json stats() const override;   // {"rules": {...}} for --log-requests

 private:
  enum class State { Reasoning, Body, Call };
  struct BlockReader;   // the open block's text and how far its calls have been read (toolcall_lfm2.cc)
  void run(std::vector<Delta>& out);
  void emit(std::vector<Delta>& out, Delta::Kind kind, std::string text);
  void read_calls(std::vector<Delta>& out, bool final);
  void close_block(std::vector<Delta>& out, bool complete);

  State state_;
  std::string buf_;   // text not yet classified
  std::unique_ptr<BlockReader> block_;
  uint32_t calls_ = 0;   // calls emitted overall (Delta::index)
  PythonicRules rules_;
  uint64_t seed_;
};

ParsedOutput parse_output_lfm2(const std::string& text, const nlohmann::json& tools);

}  // namespace server
